export const SOURCE_LIST: Source[] = Object.values(SOURCES).sort((a, b) => a.sortKey.localeCompare(b.sortKey, 'es'));

export function citeText(id: SourceId, opts: { narrative?: boolean; first?: boolean; locator?: string } = {}): string {
  const s = SOURCES[id];
  const author = opts.first && s.firstMention ? s.firstMention : s.narrativeAuthor ?? s.citeAuthor;
  const loc = opts.locator ? `, ${opts.locator}` : '';
  return opts.narrative ? `${author} (${s.year}${loc})` : `(${author}, ${s.year}${loc})`;
}
